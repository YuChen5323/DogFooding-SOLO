export function findDensity(ingredientName: string): number {
  const lowerName = ingredientName.toLowerCase().trim();
  
  for (const entry of densityDatabase) {
    if (entry.name === ingredientName || entry.nameEn === lowerName) {
      return entry.density;
    }
    if (entry.aliases.some(alias => alias.toLowerCase() === lowerName)) {
      return entry.density;
    }
    if (lowerName.includes(entry.name) || lowerName.includes(entry.nameEn)) {
      return entry.density;
    }
  }
  
  return 1;
}
